#!/usr/bin/env python3
"""H5: the launcher's F1 quick guide reads the same co-op key table as the in-game guide.

Runs the key table block of lua/coop_dev.lua (the one tools/test_coop_keys.py tests) with the real Lua 3.1
and writes the guide's co-op lines, with the default Modern bindings, as bridge/guide_keys.h.
  tools/gen_guide_keys.py          rewrite bridge/guide_keys.h
  tools/gen_guide_keys.py --check  exit 1 when the committed header is out of step (tools/test_coop_keys.py)"""
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import test_coop_keys as keys  # noqa: E402

OUT = ROOT / "bridge/guide_keys.h"

DUMP = r'''
coop.preset = "modern"
reset(nil)
coop.preset = "modern"
coop.ApplyPreset = nil
guide_rows = coop.GuideLines()
i = 1
while (i <= guide_rows.n) do
    print("ROW\t" .. guide_rows[i][1] .. "\t" .. guide_rows[i][4])
    i = i + 1
end
'''


def lua_rows(block=None, tmp=None):
    keys.ensure_lua()
    block = keys.BLOCK if block is None else block
    with tempfile.TemporaryDirectory(prefix="guide-keys-") as t:
        tmp = Path(t)
        head, tail = keys.FIXTURE.split("nfail = 0", 1)
        # the fixture's helpers (reset) come from its tail: run the stubs, the block, then the helper definitions and the dump
        funcs = tail[tail.index("function reset"):tail.index("function old_copy")]
        prog = tmp / "dump.lua"
        prog.write_text(head + "\n" + keys.pad_layer_lua() + block + "\nnfail = 0\n" + funcs + DUMP)
        r = subprocess.run([str(keys.LUA), str(prog)], capture_output=True, text=True, timeout=30)
    if r.returncode:
        raise SystemExit("guide keys: Lua failed: " + r.stderr)
    return [l.split("\t")[1:3] for l in r.stdout.splitlines() if l.startswith("ROW\t")]


def header(rows):
    out = ["/* Generated by tools/gen_guide_keys.py from the key table in lua/coop_dev.lua (H5): the co-op lines of the",
           " * launcher's quick guide, with the default bindings. Do not edit; tools/test_coop_keys.py checks it is current. */",
           "#ifndef GUIDE_KEYS_H", "#define GUIDE_KEYS_H",
           "static const struct { const char *keys, *label; } guide_coop_keys[] = {"]
    for k, d in rows:
        out.append('    { "%s", "%s" },' % (k.replace('"', '\\"'), d.replace('"', '\\"')))
    out += ["};", "#define GUIDE_COOP_KEYS ((int)(sizeof(guide_coop_keys) / sizeof(guide_coop_keys[0])))", "#endif", ""]
    return "\n".join(out)


def main():
    text = header(lua_rows())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("bridge/guide_keys.h is out of step with lua/coop_dev.lua: run tools/gen_guide_keys.py")
            return 1
        return 0
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
